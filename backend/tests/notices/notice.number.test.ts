import { describe, expect, it } from 'vitest';
import { deriveWhatsappNumber } from '../../src/modules/notices/notice.number.js';

describe('deriveWhatsappNumber', () => {
  it.each([
    ['3815550101', '5493815550101'],
    ['381 555-0101', '5493815550101'],
    ['(381) 555 0101', '5493815550101'],
    ['1155551234', '5491155551234'],
    ['+5491155551234', '5491155551234'],
    ['+54 9 11 5555-1234', '5491155551234'],
    ['541155551234', '5491155551234'],
    ['+54 381 555 0101', '5493815550101'],
    ['01155551234', '5491155551234'],
    ['0381 5550101', '5493815550101'],
    ['11 15 5555 1234', '5491155551234'],
    ['0381 15 5550101', '5493815550101'],
    ['0351 15 5123456', '5493515123456'],
  ])('turns %s into %s', (raw, expected) => {
    expect(deriveWhatsappNumber(raw)).toBe(expected);
  });

  it.each(['', '   ', 'abc', '12345', '555-0101', '381555010', '38155501012', '+1 415 555 2671', '5493815550', '549381555010199'])(
    'cannot use %j',
    (raw) => {
      expect(deriveWhatsappNumber(raw)).toBeUndefined();
    },
  );
});
